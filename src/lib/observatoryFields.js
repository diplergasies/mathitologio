const MONTHS_GEN = [
  'Ιαν.', 'Φεβ.', 'Μαρ.', 'Απρ.', 'Μαΐου', 'Ιουν.', 'Ιουλ.', 'Αυγ.', 'Σεπ.', 'Οκτ.', 'Νοε.', 'Δεκ.',
]

// Κλειδί 15νθημέρου: 'YYYY-MM-1|2'.
export function periodKey(year, month, half) {
  return `${year}-${String(month).padStart(2, '0')}-${half}`
}

// Από ημερομηνία 'YYYY-MM-DD' → { year, month, half }.
export function periodOfDate(ymd) {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(String(ymd || ''))
  if (!m) return null
  return { year: Number(m[1]), month: Number(m[2]), half: Number(m[3]) <= 15 ? 1 : 2 }
}

// Αναγνώσιμο όνομα 15νθημέρου, π.χ. «1ο 15ήμ. Οκτ. 2026».
export function periodLabel({ year, month, half }) {
  return `${half}ο 15ήμ. ${MONTHS_GEN[month - 1]} ${year}`
}
